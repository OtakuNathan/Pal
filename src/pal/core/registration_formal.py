"""Render the finite relation used by the production registration reducers."""
from __future__ import annotations

import hashlib
import json
from collections.abc import Sequence

from pal.core.registration_state import (
    RegistrationEvent, RegistrationPhase, reduce_registration,
)
from pal.shared.registration import OwnerRelation, OwnershipEvent, owner_relation, reduce_ownership


def registration_edges() -> list[tuple[str | bool, ...]]:
    rows = []
    for phase in RegistrationPhase:
        for owns in (False, True):
            for event in RegistrationEvent:
                try:
                    target = reduce_registration(phase, event, owns_registration=owns)
                except ValueError:
                    continue
                rows.append((phase.value, owns, event.value, target.value))
    return sorted(rows)


def ownership_edges() -> list[tuple[str, ...]]:
    rows = []
    for relation in OwnerRelation:
        for event in OwnershipEvent:
            try:
                target = reduce_ownership(relation, event)
            except ValueError:
                continue
            rows.append((relation.value, event.value, target.value))
    return sorted(rows)


def render_registration_relation() -> str:
    expected, other = object(), object()
    classes = [(current is None, current is expected, owner_relation(current, expected).value)
               for current in (None, expected, other)]
    rows, ownership = registration_edges(), ownership_edges()
    digest = hashlib.sha256(json.dumps([classes, rows, ownership], sort_keys=True).encode()).hexdigest()
    def atom(value: str | bool) -> str:
        return ("TRUE" if value else "FALSE") if isinstance(value, bool) else json.dumps(value)
    def table(values: Sequence[tuple[str | bool, ...]]) -> str:
        return "{\n" + ",\n".join("    <<" + ", ".join(atom(v) for v in row) + ">>" for row in values) + "\n}"
    states = "{" + ", ".join(json.dumps(p.value) for p in RegistrationPhase) + "}"
    return f'''---------------- MODULE ModuleRegistrationReducer ----------------
EXTENDS FiniteSets
\\* Generated by executing pal.core.registration_state and pal.shared.registration. Do not edit.
ReducerDigest == "{digest}"
Phases == {states}
OwnerClassifications == {table(classes)}
RegistrationEdges == {table(rows)}
OwnershipEdges == {table(ownership)}
OwnerKind(current, actor) == CHOOSE r \\in {{"vacant", "self", "other"}}:
    <<current = "none", current = actor, r>> \\in OwnerClassifications
RegistrationStep(source, owns, event, target) ==
    <<source, owns, event, target>> \\in RegistrationEdges
OwnershipStep(source, event, target) ==
    <<source, event, target>> \\in OwnershipEdges
=============================================================================
'''
