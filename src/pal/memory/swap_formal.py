"""Generate the complete finite relation by executing production swap rules."""
from __future__ import annotations

import hashlib
import json
from itertools import product
from collections.abc import Sequence

ModelAtom = str | bool | int | tuple[bool, ...]

from pal.memory.swap_state import SwapEvent, SwapFacts, SwapPhase, binding_ready, can_publish, can_sleep, can_wake, decide_launch, reduce_swap
from pal.memory.embedding_space import accepts_vector, embedding_access
from pal.shared.maintenance import MaintenanceToken, owns_maintenance


def render_swap_relation() -> str:
    facts = [SwapFacts(*values) for values in product((False, True), repeat=5)]
    edges = []
    publish = []
    launches = []
    sleep_guards = [(required, delivered) for required, delivered in product((False, True), repeat=2)
                    if can_sleep(required, delivered)]
    wake_guards = [(published, bound, released) for published, bound, released in product((False, True), repeat=3)
                   if can_wake(published, bound, released)]
    bindings = [values for values in product((False, True), repeat=3) if binding_ready(*values)]
    owners = (None, MaintenanceToken(), MaintenanceToken())
    owner_guards = [(current, requested) for current, token in enumerate(owners)
                    for requested, held in enumerate(owners) if owns_maintenance(token, held)]
    accesses = [(known, matches, writable, embedding_access(known, matches, writable).value)
                for known, matches, writable in product((False, True), repeat=3)]
    vector_guards = [(matches, 0 if expected is None else expected, dimension)
                     for matches in (False, True) for expected in (None, 2, 3) for dimension in (0, 2, 3)
                     if accepts_vector(matches, expected, dimension)]
    for phase in SwapPhase:
        for context in facts:
            values = (context.source_current, context.caught_up, context.fenced, context.published, context.indexed)
            if can_publish(phase, context):
                publish.append((phase.value, values))
            for paused in (False, True):
                launches.append((phase.value, values, paused,
                                 decide_launch(phase, context, paused=paused).value))
            for event in SwapEvent:
                try:
                    target = reduce_swap(phase, event, context)
                except ValueError:
                    continue
                edges.append((phase.value, values, event.value, target.value))
    def atom(value: ModelAtom) -> str:
        if isinstance(value, tuple):
            return "<<" + ", ".join("TRUE" if v else "FALSE" for v in value) + ">>"
        if isinstance(value, bool):
            return "TRUE" if value else "FALSE"
        if isinstance(value, int):
            return str(value)
        return json.dumps(value)
    def rows(values: Sequence[tuple[ModelAtom, ...]]) -> str:
        return "{\n" + ",\n".join("    <<" + ", ".join(atom(v) for v in row) + ">>" for row in values) + "\n}"
    digest = hashlib.sha256(json.dumps([edges, publish, launches, accesses, vector_guards, sleep_guards, wake_guards, owner_guards, bindings]).encode()).hexdigest()
    phases = "{" + ", ".join(json.dumps(p.value) for p in SwapPhase) + "}"
    return f'''---------------- MODULE MemorySwapReducer ----------------
\\* Generated by executing pal.memory.swap_state. Do not edit.
ReducerDigest == "{digest}"
Phases == {phases}
Edges == {rows(edges)}
PublishGuards == {rows(publish)}
LaunchDecisions == {rows(launches)}
EmbeddingAccesses == {rows(accesses)}
VectorGuards == {rows(vector_guards)}
SleepGuards == {rows(sleep_guards)}
WakeGuards == {rows(wake_guards)}
BindingGuards == {rows(bindings)}
MaintenanceOwners == {rows(owner_guards)}
Step(source, facts, event, target) == <<source, facts, event, target>> \\in Edges
CanPublish(source, facts) == <<source, facts>> \\in PublishGuards
DecideLaunch(source, facts, paused, decision) == <<source, facts, paused, decision>> \\in LaunchDecisions
EmbeddingAccess(known, matches, writable, access) == <<known, matches, writable, access>> \\in EmbeddingAccesses
AcceptsVector(matches, expected, dimension) == <<matches, expected, dimension>> \\in VectorGuards
CanSleep(required, delivered) == <<required, delivered>> \\in SleepGuards
CanWake(published, bound, released) == <<published, bound, released>> \\in WakeGuards
BindingReady(repository, backend, selected) == <<repository, backend, selected>> \\in BindingGuards
OwnsMaintenance(current, requested) == <<current, requested>> \\in MaintenanceOwners
=============================================================================
'''
